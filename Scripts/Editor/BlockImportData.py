"""Deterministic block-import data from Reference/minecraft-blocks-26.3; stdlib only, so it runs in editor Python.

    uv run --no-project --python 3.13 python -I Scripts/Editor/BlockImportData.py --write-tags
writes Config/Tags/MinecraftBlockTags.ini (the vanilla block tags as Block.* gameplay tags). The editor must
start with that file in place before ImportBlocks.py runs, because gameplay tags register at startup.
"""
import hashlib
import json
import sys
from pathlib import Path

REFERENCE = "Reference/minecraft-blocks-26.3"
TAGS_INI = "Config/Tags/MinecraftBlockTags.ini"
# Declared natively in Source/Unnamed/Foundation/FoundationTags.cpp; the ini must not repeat them.
NATIVE_TAGS = {"Block.Mineable.Pickaxe", "Block.IncorrectForTool.Iron", "Block.PreventsNearbyLeafDecay", "Block.Snow"}
# Face code layout: FoundationBlockFaces in Source/Unnamed/Foundation/FoundationBlockRegistry.h.
TRANSFORM_SHIFT, TINT_BIT, CULL_BIT, OVERLAY_BIT, OVERLAY_FACE_SHIFT = 10, 1 << 13, 1 << 14, 1 << 15, 16
# 26.3 getStateForPlacement families (javap of each block class); see EFoundationPlacementRule.
FACING_NEAREST = {"observer"}
FACING_AWAY_NEAREST = {"dispenser", "dropper", "barrel", "command_block", "chain_command_block",
                       "repeating_command_block"}
ORIENTATION = {"crafter": "CRAFTER_ORIENTATION", "jigsaw": "JIGSAW_ORIENTATION"}
# Model blocks with a placement rule of their own; the rest place their default state until phase 6 S7.
MODEL_PLACEMENT = {"wall_torch": "WALL_ATTACHED"}
# Model quad code layout: FoundationBlockModels in Source/Unnamed/Foundation/FoundationBlockRegistry.h. Faces are
# EFoundationFace (West, East, North, South, Down, Up).
FACES = ["west", "east", "north", "south", "down", "up"]
OFFSET_KINDS = {None: "NONE", "xz": "XZ", "xyz": "XYZ"}


def unreal_point(p):
    """Mojang block space (x east, y up, z south) -> Unreal block space (X east, Y south, Z up)."""
    return [p[0], p[2], p[1]]


def unreal_box(b):
    return unreal_point(b[:3]) + unreal_point(b[3:])


def quad_code(quad, index):
    face = FACES.index
    return (index[quad["t"]] | (quad["tint"] + 1) << 10 | (face(quad["cull"]) + 1 if quad["cull"] else 0) << 12 |
            face(quad["facing"]) << 15 | face(quad["shade"]) << 18 | quad["light"] << 21)


def pascal(snake):
    return "".join(part[:1].upper() + part[1:] for part in snake.split("_"))


def tag_name(vanilla):
    """minecraft block tag -> project gameplay tag: mineable/pickaxe -> Block.Mineable.Pickaxe,
    needs_iron_tool -> Block.NeedsTool.Iron, incorrect_for_iron_tool -> Block.IncorrectForTool.Iron, the rest
    by path segment: base_stone_overworld -> Block.BaseStoneOverworld."""
    if vanilla.startswith("needs_") and vanilla.endswith("_tool"):
        return "Block.NeedsTool." + pascal(vanilla[len("needs_"):-len("_tool")])
    if vanilla.startswith("incorrect_for_") and vanilla.endswith("_tool"):
        return "Block.IncorrectForTool." + pascal(vanilla[len("incorrect_for_"):-len("_tool")])
    return "Block." + ".".join(pascal(segment) for segment in vanilla.split("/"))


def load(root):
    ref = Path(root) / REFERENCE
    read = lambda name: json.loads((ref / name).read_text(encoding="utf-8"))
    return ref, read("block_manifest.json"), read("block_states.json"), read("textures.json"), read("items.json"), \
        read("facts/creative_tabs.json"), read("block_models.json"), read("facts/block_state_facts.json"),         read("facts/block_support.json")


def source_sha256(root):
    """Hash of the reference's file list (which hashes every file): an import from different data refuses to
    overwrite assets made from this one."""
    return hashlib.sha256((Path(root) / REFERENCE / "SHA256SUMS.txt").read_bytes()).hexdigest()


def tags_ini(root):
    _, manifest, _, _, _, _, _, _, _ = load(root)
    tags = sorted({t for b in manifest["blocks"] for t in b["tags"]})
    lines = ["; Generated by Scripts/Editor/BlockImportData.py from Reference/minecraft-blocks-26.3: every vanilla",
             "; block tag an imported block carries, as a Block.* gameplay tag. Do not edit; regenerate.",
             "[/Script/GameplayTags.GameplayTagsList]"]
    names = {}
    for tag in tags:
        name = tag_name(tag)
        assert names.setdefault(name, tag) == tag, f"two vanilla tags map to {name}"
        if name not in NATIVE_TAGS:
            lines.append(f'GameplayTagList=(Tag="{name}",DevComment="#minecraft:{tag}")')
    return "\n".join(lines) + "\n"


def placement_rule(block):
    """The block's placement family, from its id and properties. Model blocks place their default state until the
    plant interaction session (phase 6, S7) brings their rules."""
    props = {p.split("=")[0] for p in block["properties"].split(";") if p}
    bid = block["id"]
    if bid in ORIENTATION:
        return ORIENTATION[bid]
    if "type" in props and block["shape"] == "slab":
        return "SLAB"
    if "axis" in props:
        return "AXIS"
    if "facing" in props:
        values = next(p for p in block["properties"].split(";") if p.startswith("facing=")).split("=")[1].split("|")
        if set(values) == {"north", "south", "west", "east"}:
            return "FACING_PLAYER"
        if bid in FACING_NEAREST:
            return "FACING_NEAREST"
        assert bid in FACING_AWAY_NEAREST, f"unmapped six-way facing block {bid}"
        return "FACING_AWAY_NEAREST"
    if "persistent" in props and "distance" in props:
        return "LEAVES"
    if "snowy" in props:
        return "SNOWY"
    assert "orientation" not in props, bid
    return "DEFAULT"


def color(hex_text):
    """'#91BD59' -> (r, g, b, 255); None -> untinted (0, 0, 0, 0)."""
    if not hex_text:
        return (0, 0, 0, 0)
    value = int(hex_text.lstrip("#"), 16)
    return (value >> 16 & 255, value >> 8 & 255, value & 255, 255)


def build(root):
    """Everything ImportBlocks.py writes, as plain data."""
    ref, manifest, states, textures, items, tabs, models, facts, support = load(root)
    # Asset texture 0 is plain white (project blocks); reference textures follow, so index = position + 1.
    texture_list = [{"name": "white", "water_flow": False, "first_layer": textures["arrays"]["blocks"]["layers"],
                     "frame_count": 1, "frame_indices": [], "frame_ticks": [], "interpolate": False, "png": "white",
                     "mipmap_strategy": "mean", "alpha_cutoff_bias": 0.0}]
    for t in textures["textures"]:
        anim = t.get("animation")
        texture_list.append({"name": t["name"], "water_flow": t["array"] == "water_flow",
                             "first_layer": t["first_layer"], "frame_count": t["frame_count"],
                             "frame_indices": [f["index"] for f in anim["frames"]] if anim else [],
                             "frame_ticks": [f["time"] for f in anim["frames"]] if anim else [],
                             "interpolate": bool(anim and anim["interpolate"]),
                             # Stand-in tiles (the chests') are derived files outside assets/: textures.json names them.
                             "png": str(ref / t["file"]) if "file" in t else
                                    str(ref / f"assets/minecraft/textures/block/{t['name']}.png"),
                             "mipmap_strategy": t["mipmap_strategy"], "alpha_cutoff_bias": t.get("alpha_cutoff_bias", 0.0),
                             "layer_rgba_sha256": t["layer_rgba_sha256"], "frame_size": t["frame_size"]})
    index = {t["name"]: i for i, t in enumerate(texture_list)}

    def layers(array):
        """(png, frame, strategy, alpha cutoff bias) per layer of one array, in layer order."""
        out = []
        for t in texture_list:
            if t["water_flow"] != (array == "water_flow"):
                continue
            for frame in range(t["frame_count"]):
                out.append((t["first_layer"] + frame, t["png"], frame, t["mipmap_strategy"], t["alpha_cutoff_bias"]))
        out.sort()
        assert [l[0] for l in out] == list(range(len(out))), f"{array} layers are not contiguous"
        return [l[1:] for l in out]

    def face_codes(state):
        codes = []
        for face in state["faces"]:
            code = index[face["t"]] | face["x"] << TRANSFORM_SHIFT | (TINT_BIT if face["tint"] >= 0 else 0) | (
                CULL_BIT if face["cull"] else 0)
            codes.append(code)
        overlays = [(i, f["overlay"]) for i, f in enumerate(state["faces"]) if "overlay" in f]
        overlay = 0
        if overlays:
            assert len({(o["t"], o["tint"]) for _, o in overlays}) == 1, "one overlay texture per state"
            first = overlays[0][1]
            overlay = index[first["t"]] | (TINT_BIT if first["tint"] >= 0 else 0) | OVERLAY_BIT
            for face, _ in overlays:
                overlay |= 1 << (OVERLAY_FACE_SHIFT + face)
        return codes + [overlay]

    state_blocks = {b["id"]: b for b in states["blocks"]}
    item_by_block = {i["block"]: i for i in items["items"]}
    shapes = {"full": "FULL", "slab_bottom": "SLAB_BOTTOM", "slab_top": "SLAB_TOP", "fluid": "FLUID", "model": "MODEL",
              **{f"layers_{k}": f"LAYERS{k}" for k in range(1, 8)}}
    # Baked models: quad vertices (Unreal axes, then UV) and codes; models as quad ranges.
    model_list, quad_vertices, quad_codes = [], [], []
    for model in models["models"]:
        model_list.append({"first_quad": len(quad_codes), "quad_count": len(model["quads"]), "ao": model["ao"]})
        for quad in model["quads"]:
            for p, uv in zip(quad["v"], quad["uv"]):
                quad_vertices += unreal_point(p) + uv
            quad_codes.append(quad_code(quad, index))
    # Item sprites under textures/item join the icon atlas after the block array's layers (white included).
    block_layer_count = textures["arrays"]["blocks"]["layers"] + 1
    item_sprites = sorted({layer["texture"] for i in items["items"] for layer in i.get("icon", {}).get("sprite", [])
                           if layer["texture"].startswith("item/")})
    sprite_pngs = [str(ref / f"assets/minecraft/textures/{name}.png") for name in item_sprites]

    def icon_fields(item):
        icon = item.get("icon") if item else None
        if not icon:
            return {"item_icon_tile": -1, "item_icon_model": -1}
        if "sprite" in icon:
            (layer,) = icon["sprite"]
            name = layer["texture"]
            tile = (block_layer_count + item_sprites.index(name) if name.startswith("item/")
                    else texture_list[index[name.removeprefix("block/")]]["first_layer"])
            return {"item_icon_tile": tile, "item_icon_model": -1}
        gui = icon["gui"]
        return {"item_icon_tile": -1, "item_icon_model": icon["model"], "item_icon_rotation": gui["rotation"],
                "item_icon_translation": gui["translation"], "item_icon_scale": gui["scale"]}

    facts_by_id = {b["id"]: b for b in facts["blocks"]}
    support_by_id = {b["id"]: b["support"] for b in support["blocks"]}
    # A standing-and-wall item's wall block, for the attachments the support table measures (the torch); the coral
    # fans' wall fans wait until their own attachment is measured.
    wall_blocks = {e["standing"]: e["wall"] for e in support["items"] if e["standing"] == support["probes"]["up"]}

    def model_fields(block, entry):
        """Per-state parts, boxes, light and water, the offset and the facts' replaceable flag of a model block."""
        fact = facts_by_id[block["id"]]
        by_state = {s["id"]: s for s in fact["states"]}
        state_models, counts, boxes, light, water = [], [], [], [], []
        for state in entry["states"]:
            state_models.append(len(state["model"]))
            for part in state["model"]:
                state_models += [len(part)] + part
            f = by_state[state["id"]]
            counts += [len(f["outline"]), len(f["collision"])]
            boxes += [c for b in f["outline"] + f["collision"] for c in unreal_box(b)]
            light.append(f["light"])
            fluid = f["fluid"]
            assert fluid is None or fluid["fluid"] == "minecraft:water", (block["id"], fluid)
            water.append(fluid["amount"] if fluid else 0)
        replaceable = {s["replaceable"] for s in fact["states"]}
        assert len(replaceable) == 1, block["id"]
        offset = fact["offset"] or {}
        return {"state_models": state_models, "state_box_counts": counts, "state_boxes": boxes, "state_light": light,
                "state_water": water, "offset_kind": OFFSET_KINDS[offset.get("kind")],
                "offset_max_horizontal": offset.get("max_xz", 0.0), "offset_min_vertical": offset.get("min_y", 0.0),
                "outline_moves_with_offset": offset.get("outline_moves", False),
                "collision_moves_with_offset": offset.get("collision_moves", False),
                "replaceable": replaceable.pop()}
    def cube_light_fields(block, entry):
        """Per-state light of a full-cube or slab block, from the facts, when a state's light differs from the block's
        (a lit furnace, smoker, blast furnace, redstone ore or lamp); the others keep the block's one light."""
        by_state = {s["id"]: s for s in facts_by_id[block["id"]]["states"]}
        light = [by_state[s["id"]]["light"] for s in entry["states"]]
        return {"state_light": light} if any(v != block.get("light_emission", 0) for v in light) else {}
    fluid_ids = {f["id"] for f in manifest["fluids"]}
    blocks = []
    for block in manifest["blocks"] + manifest["fluids"]:
        bid = block["id"]
        entry = state_blocks[bid]
        # Fluids (water, lava) have no faces of their own: the runtime draws their still and flow textures.
        water = bid in fluid_ids
        default = next(s for s in entry["states"] if s["id"] == entry["default_state_id"])
        item = item_by_block.get(bid)
        model = block.get("shape") == "model"
        if model:
            first = models["models"][next(s for s in entry["states"] if s["id"] == entry["default_state_id"])["model"][0][0]]
        blocks.append({
            "id": bid, "name": block["name"], "protocol_id": block["protocol_id"],
            "min_state_id": entry["min_state_id"], "default_state_id": entry["default_state_id"],
            "properties": entry["properties"], "hardness": block["hardness"],
            "blast_resistance": block["blast_resistance"],
            "requires_correct_tool_for_drops": block.get("requires_correct_tool_for_drops", False),
            "light_emission": block.get("light_emission", 0), "replaceable": water,
            "layer": block["material_layer"].upper(),
            "placement": MODEL_PLACEMENT.get(bid, "DEFAULT") if water or model else placement_rule(block),
            "tint": color((block.get("tint") or {}).get("color")),
            "tags": [tag_name(t) for t in block.get("tags", [])],
            "state_shapes": [shapes[s["shape"]] for s in entry["states"]],
            "state_faces": [c for s in entry["states"] for c in (([0] * 7) if water or model else face_codes(s))],
            # The default state's top face (a model's first quad), for the particle color.
            "particle_texture": None if water else first["quads"][0]["t"] if model else default["faces"][5]["t"],
            "item": item["id"] if item else None, "item_name": item["name"] if item else "",
            "item_wall_block": wall_blocks.get(bid) if item else None, "state_support": support_by_id[bid],
            "item_max_stack": item["max_stack"] if item else 64, "item_tint": color(item["gui_tint"] if item else None),
            **icon_fields(item),
            **(model_fields(block, entry) if model else ({} if water else cube_light_fields(block, entry))),
            # Survival B1's family blocks (the manifest's added: "survival-B1"), behind foundation.Blocks.Families.
            "appended_family": block.get("added") == "survival-B1",
            # 26.3 draws the chests as block entities (ENTITYBLOCK_ANIMATED): no block mesh (survival B4a).
            "draws_no_mesh": block.get("template") == "chests",
        })
    creative = []
    meta = {t["id"]: t for t in items["creative_tabs"]}
    for tab in tabs:
        m = meta[tab["id"]]
        creative.append({"id": tab["id"].removeprefix("minecraft:"), "title": m["title"],
                         "row": 0 if m["row"] == "TOP" else 1, "column": m["column"], "type": m["type"],
                         "aligned_right": m["aligned_right"], "show_title": m["show_title"],
                         "can_scroll": m["can_scroll"], "icon": m["icon"].removeprefix("minecraft:"),
                         "items": [(e if isinstance(e, str) else e["id"]).removeprefix("minecraft:")
                                   for e in tab["display"]]})
    return {"source_sha256": source_sha256(root), "textures": texture_list, "index": index,
            "block_layers": layers("blocks"), "flow_layers": layers("water_flow"), "blocks": blocks,
            "creative_tabs": creative, "water_color": color(textures["plains"]["water"]), "models": model_list,
            "quad_vertices": quad_vertices, "quad_codes": quad_codes, "sprite_pngs": sprite_pngs,
            "tags_ini": tags_ini(root)}


def main():
    root = Path(__file__).resolve().parents[2]
    if "--write-tags" in sys.argv:
        path = root / TAGS_INI
        path.parent.mkdir(exist_ok=True)
        path.write_text(tags_ini(root), encoding="utf-8")
        print("wrote", path)
    data = build(root)
    print(f"{len(data['blocks'])} blocks, {len(data['textures'])} textures, {len(data['block_layers'])} block layers, "
          f"{len(data['flow_layers'])} water flow layers, {len(data['creative_tabs'])} creative tabs, "
          f"{len(data['models'])} models, {len(data['quad_codes'])} quads, {len(data['sprite_pngs'])} item sprites")


if __name__ == "__main__":
    main()
