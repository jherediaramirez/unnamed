"""Deterministic item-import data from Reference/minecraft-items-26.3; stdlib only, so it runs in editor Python.

    uv run --no-project --python 3.13 python -I Scripts/Editor/ItemImportData.py --write-tags
writes Config/Tags/MinecraftItemTags.ini (the vanilla item tags as Item.* gameplay tags). The editor must start
with that file in place before ImportItems.py runs, because gameplay tags register at startup.
"""
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # python -I leaves the script's folder off the path
from BlockImportData import pascal, tag_name as block_tag_name  # noqa: E402

REFERENCE = "Reference/minecraft-items-26.3"
ASSETS = "assets/minecraft/textures/"
TAGS_INI = "Config/Tags/MinecraftItemTags.ini"
# The item components report the reference copies (the rarity: the tooltip name's colour).
COMPONENT_REPORT = "reports/components/item"
# GUI stand-ins for items 26.3 draws as a special model (Scripts/Editor/CreateShieldSprite.py; Docs/StandIns.md).
STAND_IN_SPRITES = {"shield": "Art/StandIns/item/shield.png"}
# Declared natively in Source/Unnamed/Foundation/FoundationTags.cpp; no vanilla item tag may map onto them.
NATIVE_TAGS = {"Item.Block"}
# Survival B1: a sapling item places the sapling block of the same id once the blocks reference holds that block.
BLOCK_MANIFEST = "Reference/minecraft-blocks-26.3/block_manifest.json"
SAPLINGS = {wood + "_sapling" for wood in
            ("oak", "spruce", "birch", "jungle", "acacia", "cherry", "dark_oak", "pale_oak", "poplar")}


def item_tag_name(vanilla):
    """minecraft item tag -> project gameplay tag by path segment: enchantable/mining_loot ->
    Item.Enchantable.MiningLoot (the block tags' naming)."""
    return "Item." + ".".join(pascal(segment) for segment in vanilla.split("/"))


def rule_block_tag(selector):
    """A tool rule's block selector -> the Block.* tag it names, or "" for a single block (minecraft:cobweb)."""
    return block_tag_name(selector[len("#minecraft:"):]) if selector.startswith("#minecraft:") else ""


def load(root):
    ref = Path(root) / REFERENCE
    read = lambda name: json.loads((ref / name).read_text(encoding="utf-8"))
    return ref, read("items.json"), read("models.json"), read("textures.json"), read("tags.json"), read("lang.json")


def verify_hashes(root):
    """Every file SHA256SUMS.txt lists must match, and no other file may be present. The full verifier
    (tools/verify_reference.py) needs Pillow, which editor Python lacks; this is its hash step."""
    ref = Path(root) / REFERENCE
    listed = {}
    for line in (ref / "SHA256SUMS.txt").read_text(encoding="utf-8").splitlines():
        digest, name = line.split(None, 1)
        listed[name.lstrip("*")] = digest
    for name, digest in listed.items():
        if hashlib.sha256((ref / name).read_bytes()).hexdigest() != digest:
            raise RuntimeError(f"{REFERENCE}/{name} does not match SHA256SUMS.txt")
    present = {p.relative_to(ref).as_posix() for p in ref.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
    unlisted = sorted(present - set(listed) - {"SHA256SUMS.txt"})
    if unlisted:
        raise RuntimeError(f"{REFERENCE} has unlisted files: {unlisted[:5]}")
    return len(listed)


def source_sha256(root):
    """Hash of the reference's file list (which hashes every file): an import from different data refuses to
    overwrite assets made from this one."""
    return hashlib.sha256((Path(root) / REFERENCE / "SHA256SUMS.txt").read_bytes()).hexdigest()


def tags_ini(root):
    tags = load(root)[4]
    lines = ["; Generated by Scripts/Editor/ItemImportData.py from Reference/minecraft-items-26.3: every vanilla",
             "; item tag in its tags.json, as an Item.* gameplay tag. Do not edit; regenerate.",
             "[/Script/GameplayTags.GameplayTagsList]"]
    names = {}
    for tag in sorted(tags["item"]):
        name = item_tag_name(tag)
        assert names.setdefault(name, tag) == tag, f"two vanilla tags map to {name}"
        assert name not in NATIVE_TAGS and not name.startswith("Item.Block."), f"{tag} maps onto a native tag"
        lines.append(f'GameplayTagList=(Tag="{name}",DevComment="#minecraft:{tag}")')
    return "\n".join(lines) + "\n"


def modifier(m):
    """An attribute modifier verbatim, without namespaces. The tooltip code knows add_value only."""
    assert m["operation"] == "add_value", f"modifier operation {m['operation']}: add the tooltip's other forms first"
    return {"attribute": m["type"].removeprefix("minecraft:"), "id": m["id"].removeprefix("minecraft:"),
            "amount": float(m["amount"]), "operation": m["operation"], "slot": m["slot"]}


def argb(value):
    """A tint's packed ARGB int (the dye's default -6265536) as [r, g, b, a] bytes, sRGB like the sprites."""
    value &= 0xFFFFFFFF
    return [(value >> 16) & 255, (value >> 8) & 255, value & 255, value >> 24]


def layer_tints(case, layers):
    """One colour per layer: the case's tint (a dye's default), white where it has none; empty when untinted."""
    tints = case.get("tints") or []
    if not tints:
        return []
    return [argb(tints[i]["default"]) if i < len(tints) and tints[i] else [255, 255, 255, 255]
            for i in range(len(layers))]


def vector(values):
    return [float(v) for v in values]


def shield_fields(item):
    """The special model and blocks_attacks of the shield (survival step 19b); defaults for every other item."""
    special, blocks = item.get("special"), item.get("blocks_attacks")
    out = {"gui_sprite": "item/" + item["id"] if item["id"] in STAND_IN_SPRITES else "",
           "special_model": special["type"] if special else "",
           "special_texture": special["texture"] if special else "",
           "special_scale": vector(special["transformation"]["scale"]) if special else vector([1, 1, 1]),
           "blocks_attacks": blocks is not None}
    if special:
        transform = special["transformation"]
        assert transform["translation"] == [0.0, 0.0, 0.0] and transform["left_rotation"] == [0.0, 0.0, 0.0, 1.0] and \
            transform["right_rotation"] == [0.0, 0.0, 0.0, 1.0], f"{item['id']}: only a scale transformation is handled"
    if blocks:
        reductions = blocks["damage_reductions"]
        assert len(reductions) == 1 and "type" not in reductions[0], f"{item['id']}: one all-damage reduction only"
        out.update({"block_delay_seconds": float(blocks["block_delay_seconds"]),
                    "disable_cooldown_scale": float(blocks["disable_cooldown_scale"]),
                    "block_angle_degrees": float(reductions[0]["horizontal_blocking_angle"]),
                    "block_base": float(reductions[0]["base"]), "block_factor": float(reductions[0]["factor"]),
                    "item_damage_threshold": float(blocks["item_damage"]["threshold"]),
                    "item_damage_base": float(blocks["item_damage"]["base"]),
                    "item_damage_factor": float(blocks["item_damage"]["factor"]),
                    "bypassed_by": (blocks["bypassed_by"] or "").removeprefix("#minecraft:"),
                    "block_sound": (blocks["block_sound"] or "").removeprefix("minecraft:"),
                    "disabled_sound": (blocks["disabled_sound"] or "").removeprefix("minecraft:")})
    return out


def build(root):
    ref, items, models, textures, tags, lang = load(root)
    manifest = json.loads((Path(root) / BLOCK_MANIFEST).read_text(encoding="utf-8"))
    block_ids = {block["id"] for block in manifest["blocks"]}
    out_items = []
    for item in items["items"]:
        tool, weapon, attack, repair = item["tool"], item["weapon"], item["attack"], item["repair"]
        gui = item["model"]["models"][0]["model"]
        special = item.get("special")
        # The GUI sprite: item/<id>, or the block texture a sapling's item model uses (block/<id>); a special model
        # (the shield) has no layers and takes its stand-in sprite.
        assert gui == "item/" + item["id"] and (
            item["textures"][0] in ("item/" + item["id"], "block/" + item["id"]) if not special else
            not item["textures"] and item["id"] in STAND_IN_SPRITES), \
            f"{item['id']}: the GUI sprite is not item/<id> or block/<id>"
        rules = []
        for rule in (tool or {}).get("rules", []):
            rules.append({"blocks": rule["blocks"], "block_tag": rule_block_tag(rule["blocks"]),
                          "speed": float(rule.get("speed", 0.0)),
                          "states_correct_for_drops": "correct_for_drops" in rule,
                          "correct_for_drops": bool(rule.get("correct_for_drops", False))})
        armor, equip = item.get("armor"), item.get("equippable")
        components = json.loads((ref / COMPONENT_REPORT / (item["id"] + ".json")).read_text(encoding="utf-8"))[
            "components"]
        rarity = components.get("minecraft:rarity", "common")
        # damage_resistant (Codex review 31 #4): the damage type tag the item resists, in entity form and worn.
        resistant = components.get("minecraft:damage_resistant", {}).get("types", "")
        assert resistant in ("", "#minecraft:is_fire"), f"{item['id']}: damage_resistant {resistant} is not handled"
        cases = []
        for case in item["model"]["models"]:
            when = case["when"]
            # A using_item condition (the shield) selects on the use, not on the display context.
            using = when is not None and when["property"] == "using_item"
            contexts = [] if when is None or using or when["is"] == "fallback" else \
                ([when["is"]] if isinstance(when["is"], str) else list(when["is"]))
            cases.append({"model": case["model"], "contexts": contexts,
                          "using_item": (1 if when["is"] == [True] else 0) if using else -1})
        out_items.append({
            "id": item["id"], "display_name": item["name"], "protocol_id": item["protocol_id"],
            "group": item["group"] or "", "material": item["material"] or "", "kind": item["kind"] or "",
            "max_stack": item["max_stack"], "max_damage": item["max_damage"] or 0,
            # No attribute modifiers: the player's own base attack damage 1 and attack speed 4.
            "attack_damage": float(attack["damage"]) if attack else 1.0,
            "attacks_per_second": float(attack["speed"]) if attack else 4.0,
            "modifiers": [modifier(m) for m in (attack or armor or {}).get("modifiers", [])],
            "tool": tool is not None,
            "default_mining_speed": float(tool["default_mining_speed"]) if tool else 1.0,
            "rules": rules,
            # Mining wears only items with a tool component; hits wear only items with a weapon component.
            "damage_per_block": tool["damage_per_block"] if tool else 0,
            "can_destroy_blocks_in_creative": tool["can_destroy_blocks_in_creative"] if tool else True,
            "damage_per_hit": weapon["item_damage_per_attack"] if weapon else 0,
            "disable_blocking_seconds": float(weapon["disable_blocking_for_seconds"]) if weapon else 0.0,
            "enchantability": item["enchantability"] or 0,
            "repair_selector": repair["items"] if repair else "",
            "repair_items": list(repair["resolved"]) if repair else [],
            "item_tags": [item_tag_name(tag) for tag in item["item_tags"]],
            "creative": [{"tab": c["tab"], "index": c["index"]} for c in item["creative"]],
            "model_type": item["model"]["type"], "models": cases,
            "swap_animation_scale": float(item["model"]["swap_animation_scale"]),
            "hand_animation_on_swap": bool(item["model"]["hand_animation_on_swap"]),
            "textures": list(item["textures"]),
            "places_block": item["id"] if item["id"] in SAPLINGS and item["id"] in block_ids else "",
            # Armor (survival step 19a2): the equippable component and the summed armor attributes.
            "equipment_slot": equip["slot"] if equip else "",
            "swappable": bool(equip["swappable"]) if equip else True,
            "equip_sound": equip["equip_sound"].removeprefix("minecraft:") if equip else "",
            "armor": float(armor["armor"]) if armor else 0.0,
            "armor_toughness": float(armor["toughness"]) if armor else 0.0,
            "knockback_resistance": float(armor["knockback_resistance"]) if armor else 0.0,
            "layer_tints": layer_tints(item["model"]["models"][0], item["textures"]),
            "rarity": rarity,
            "damage_resistant": resistant.removeprefix("#minecraft:"),
            **shield_fields(item),
        })
    out_models = []
    for model in models["models"]:
        display = []
        for context, transform in model["display"].items():
            display.append({"context": context, "rotation": vector(transform.get("rotation", [0, 0, 0])),
                            "translation": vector(transform.get("translation", [0, 0, 0])),
                            "scale": vector(transform.get("scale", [1, 1, 1]))})
        out_models.append({"name": model["id"], "parent": model["parent"] or "", "layers": list(model["layers"]),
                           "gui_light": model["gui_light"] or "", "display": display})
    # Each sprite is a layer of T_ItemTextures (16 x 16) or T_ItemTextures32 (the spears' 32 x 32 in-hand sprites),
    # in textures.json order.
    out_textures, layers = [], {16: [], 32: []}
    for texture in textures["textures"]:
        size = texture["size"]
        assert size[0] == size[1] and size[0] in layers, f"{texture['name']}: no array for size {size}"
        out_textures.append({"name": texture["name"], "width": size[0], "height": size[1],
                             "opaque_pixels": texture["opaque_pixels"], "rgba_sha256": texture["rgba_sha256"],
                             "mask": list(texture["mask"]), "layer": len(layers[size[0]])})
        layers[size[0]].append(ref / ASSETS / (texture["name"] + ".png"))
    # GUI sprites (ImportItems.py, Gui/<folder>/<name>): every item texture, and the block textures an item's model uses
    # (the saplings' block/<id>_sapling).
    sprite_pngs = sorted((ref / "assets/minecraft/textures/item").glob("*.png")) + sorted(
        ref / ASSETS / (t["name"] + ".png") for t in textures["textures"] if t["name"].startswith("block/"))
    # Then the GUI stand-ins (Gui/item/<id>) and the special models' entity textures (Gui/<folder>/<name>, e.g.
    # Gui/shield/shield_base_nopattern), after every earlier sprite.
    sprite_pngs += [Path(root) / STAND_IN_SPRITES[i["id"]] for i in items["items"] if i["id"] in STAND_IN_SPRITES]
    sprite_pngs += [ref / ASSETS / (i["special"]["texture"] + ".png") for i in items["items"] if i.get("special")]
    loot = json.loads((ref / "loot_tables.json").read_text(encoding="utf-8"))
    return {"source_sha256": source_sha256(root), "items": out_items, "models": out_models,
            "textures": out_textures, "sprite_pngs": sprite_pngs, "tags_ini": tags_ini(root),
            "array_layers": layers[16], "array_layers32": layers[32], "lang": dict(lang["keys"]),
            "loot_tables": [loot_table(t) for t in loot["tables"]],
            "loot_predicates": [{"name": p["name"], "items": list(p["items"]),
                                 "enchantments": [e["id"] for e in p["enchantments"]],
                                 "enchantment_min_levels": [e["min_level"] for e in p["enchantments"]]}
                                for p in loot["predicates"]]}


def loot_table(table):
    """loot_tables.json's table -> FFoundationLootTableAsset values (items S5b). Loot step 2a: condition objects
    become the table's condition nodes (a tree names its terms by index), a candidate's predicate names stay in
    "conditions", and the "modifiers" lists keep their order."""
    nodes = []

    def node(c):
        index = len(nodes)
        if isinstance(c, str):
            nodes.append({"type": "predicate", "name": c})
            return index
        n = {"type": c["type"]}
        nodes.append(n)
        if c["type"] in ("any_of", "all_of"):
            n["terms"] = [node(t) for t in c["terms"]]
        elif c["type"] == "inverted":
            n["terms"] = [node(c["term"])]
        elif c["type"] in ("match_block", "location_check"):
            n.update(name=c["block"], state_keys=list(c["state"]), state_values=list(c["state"].values()))
            if c["type"] == "location_check":
                n["offset"] = list(c["offset"])
        elif c["type"] == "table_bonus":
            n.update(name=c["enchantment"], chances=[float(x) for x in c["chances"]])
        elif c["type"] == "random_chance":
            n["chances"] = [float(c["chance"])]
        elif c["type"] == "match_tool":
            n.update(name=c["tag"] or "", items=list(c["items"]))
        elif c["type"] == "entity_properties":
            n["name"] = c["entity"]
        return index

    def modifier(m):
        out = {"type": m["type"], "tests": [node(c) for c in m.get("conditions", [])]}
        if m["type"] == "set_count":
            out.update(min=m["count"][0], max=m["count"][1], add=m["add"])
        elif m["type"] == "limit_count":
            out.update(min=m["min"] or 0, max=m["max"] or 0, has_min=m["min"] is not None,
                       has_max=m["max"] is not None)
        elif m["type"] == "apply_bonus":
            out.update(bonus_formula=m["formula"], bonus_enchantment=m["enchantment"],
                       bonus_multiplier=float(m["bonus_multiplier"]))
        return out

    def candidate(c):
        bonus = c.get("bonus") or {}
        count = c.get("count", [1, 1])
        return {"item": c["item"], "conditions": [x for x in c["conditions"] if isinstance(x, str)],
                "count_min": count[0], "count_max": count[1], "bonus_formula": bonus.get("formula", ""),
                "bonus_enchantment": bonus.get("enchantment", ""),
                "bonus_multiplier": float(bonus.get("bonus_multiplier", 0)),
                "explosion_decay": c.get("explosion_decay", False),
                "tests": [node(x) for x in c["conditions"] if not isinstance(x, str)],
                "modifiers": [modifier(m) for m in c.get("modifiers", [])]}
    pools = [{"rolls": p["rolls"], "candidates": [candidate(c) for c in p["candidates"]],
              "tests": [node(c) for c in p.get("conditions", [])],
              "modifiers": [modifier(m) for m in p.get("modifiers", [])]} for p in table["pools"]]
    return {"block": table["block"], "pools": pools, "modifiers": [modifier(m) for m in table.get("modifiers", [])],
            "conditions": nodes}


def main():
    root = Path(__file__).resolve().parents[2]
    files = verify_hashes(root)
    if "--write-tags" in sys.argv:
        path = root / TAGS_INI
        path.parent.mkdir(exist_ok=True)
        path.write_text(tags_ini(root), encoding="utf-8")
        print("wrote", path)
    data = build(root)
    print(f"{files} reference files match their sums; {len(data['items'])} items, {len(data['models'])} models, "
          f"{len(data['textures'])} textures ({len(data['array_layers'])} + {len(data['array_layers32'])} array layers), "
          f"{len(data['sprite_pngs'])} sprites, {len(data['lang'])} lang keys, "
          f"{sum(len(i['rules']) for i in data['items'])} tool rules, {len(data['loot_tables'])} loot tables, "
          f"{len(data['loot_predicates'])} loot predicates")


if __name__ == "__main__":
    main()
